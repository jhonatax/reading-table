"""Step 3: merge candidates + AI classifications + your manual overrides into the shelf.

Inputs
  data/candidates.jsonl       from fetch_candidates.py (Open Library metadata, popularity)
  data/classifications.jsonl  from the classifier (one JSON per book id; see pipeline/CLASSIFY.md)
  data/overrides.csv          OPTIONAL hand fixes: columns id + any field to override
                              (e.g. id,include  /  id,pace,tone). Lists use "|" (violence|sentimental).
Outputs
  data/books.csv              the final shelf, human-readable (review this in a spreadsheet)
  js/books.js                 the same data for the website (generated - don't edit by hand)

    python3 pipeline/build_books.py           # build
    python3 pipeline/build_books.py --check   # validate only, exit 1 on problems (used in CI)
"""
import argparse, csv, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))
from check_chunk import problems  # noqa: E402  (same validation rules as the classifier check)

LIST_FIELDS = ("genres", "content")
INT_FIELDS = ("pace", "tone", "challenge", "pages")
CSV_COLS = ["id", "title", "author", "year", "genres", "culture", "format", "pace", "tone",
            "challenge", "pages", "length", "content", "popularity"]


def load_jsonl(p):
    return [json.loads(l) for l in p.open() if l.strip()] if p.exists() else []


def apply_overrides(cls):
    p = ROOT / "data" / "overrides.csv"
    if not p.exists():
        return 0
    n = 0
    for r in csv.DictReader(p.open()):
        o = cls.setdefault(r["id"], {"id": r["id"]})
        for k, v in r.items():
            if k == "id" or v is None or v == "":
                continue
            if k in LIST_FIELDS: v = [x for x in v.split("|") if x]
            elif k in INT_FIELDS: v = int(v)
            elif k == "include": v = v.strip().lower() in ("1", "true", "yes")
            o[k] = v
        n += 1
    return n


def length_of(pages):
    return "short" if pages < 250 else ("medium" if pages <= 400 else "long")


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    cands = {c["id"]: c for c in load_jsonl(ROOT / "data" / "candidates.jsonl")}
    cls = {c["id"]: c for c in load_jsonl(ROOT / "data" / "classifications.jsonl")}
    n_over = apply_overrides(cls)

    errors, books, seen, stale = [], [], {}, 0
    for bid, c in cls.items():
        if bid not in cands:  # dropped out of the candidate list on a later fetch: ignore
            stale += 1; continue
        for p in problems(c):
            errors.append(f"{bid}: {p}")
        if not c.get("include") or problems(c):
            continue
        b = {
            "id": bid, "title": c["title"].strip(), "author": c["author"].strip(),
            "year": cands[bid].get("year"), "genres": c["genres"], "culture": c["culture"],
            "format": c["format"], "pace": c["pace"], "tone": c["tone"], "challenge": c["challenge"],
            "pages": c["pages"], "length": length_of(c["pages"]), "content": c["content"],
            "popularity": cands[bid].get("popularity", 0),
        }
        key = norm(b["title"]) + "|" + norm(b["author"])
        if key in seen:  # same book from two Open Library records: keep the more popular one
            if b["popularity"] > seen[key]["popularity"]:
                books[books.index(seen[key])] = b; seen[key] = b
            continue
        seen[key] = b; books.append(b)

    unclassified = [i for i in cands if i not in cls]
    books.sort(key=lambda b: -b["popularity"])
    print(f"candidates {len(cands)} | classified {len(cls)} | overrides {n_over} | "
          f"unclassified {len(unclassified)} | stale {stale} | on shelf {len(books)} | problems {len(errors)}")
    for e in errors[:30]: print("  " + e)
    if unclassified:
        print("  unclassified ids (run the classifier):", unclassified[:20])
    if args.check:
        sys.exit(1 if errors or not books else 0)

    with (ROOT / "data" / "books.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_COLS); w.writeheader()
        for b in books:
            w.writerow({**b, "genres": "|".join(b["genres"]), "content": "|".join(b["content"])})

    web = [{"id": b["id"], "t": b["title"], "a": b["author"], "y": b["year"], "genres": b["genres"],
            "culture": b["culture"], "pace": b["pace"], "tone": b["tone"], "challenge": b["challenge"],
            "length": b["length"], "format": b["format"], "content": b["content"], "pop": b["popularity"]}
           for b in books]
    js = ("/* GENERATED by pipeline/build_books.py from data/books.csv - do not edit by hand. */\n"
          "window.RT_BOOKS = [\n" + ",\n".join(json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in web) + "\n];\n")
    (ROOT / "js" / "books.js").write_text(js)
    print(f"wrote data/books.csv and js/books.js ({len(js) // 1024} KB)")
    if errors:
        print("NOTE: books with problems were left off the shelf; fix them in data/overrides.csv")


if __name__ == "__main__":
    main()
